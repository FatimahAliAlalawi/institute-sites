<?php

namespace Database\Seeders;

use App\Models\Course;
use App\Models\CourseCategory;
use App\Models\Instructor;
use App\Models\Setting;
use Illuminate\Database\Seeder;

/** دورة مسجلة تجريبية بنظام "درس يوميًا" توضّح طريقة عمل المنصة — قابلة للتعديل أو الحذف */
class LmsSeeder extends Seeder
{
    public function run(): void
    {
        Setting::put([
            'study_days' => '0,1,2,3,4',
            'certificate_title' => 'شهادة إتمام',
            'certificate_text' => 'يشهد :site بأن المتدرب/ـة',
            'certificate_signer_title' => 'إدارة المعهد',
            'payment_instructions' => 'بعد التحويل، ارفع صورة الإيصال هنا وسيتم تفعيل الدورة في حسابك خلال يوم عمل.',
            'reviews_need_approval' => '0',
        ]);

        $category = CourseCategory::firstOrCreate(['name' => 'التطوير المهني'], ['sort' => 1]);
        CourseCategory::firstOrCreate(['name' => 'التقنية والحاسب'], ['sort' => 2]);
        CourseCategory::firstOrCreate(['name' => 'الأسرة والمجتمع'], ['sort' => 3]);

        $instructor = Instructor::firstOrCreate(['name' => 'فريق التدريب — معهد البصائر'], [
            'title' => 'مدربون معتمدون',
            'bio' => 'فريق التدريب في معهد البصائر العالي للتدريب، تحت إشراف المؤسسة العامة للتدريب التقني والمهني.',
        ]);

        $title = 'الوعي بالأمن السيبراني للموظفين (دورة مسجلة — نموذج)';
        if (Course::where('title', $title)->exists()) {
            return;
        }

        $course = Course::create([
            'category_id' => $category->id,
            'instructor_id' => $instructor->id,
            'title' => $title,
            'summary' => 'دورة مسجلة تُفتح دروسها درسًا واحدًا في كل يوم دراسة، مع تحضير يومي وشهادة إتمام. (نموذج توضيحي — عدّله أو احذفه)',
            'description' => "مثال على الدورات المسجلة في المنصة:\n- يُفتح للمتدرب درس جديد في كل يوم دراسة (الأحد إلى الخميس افتراضيًا).\n- إكمال درس اليوم يُسجَّل حضورًا، ويوم الدراسة بدون إكمال يُسجَّل غيابًا.\n- تقدر تخصص أيامًا مختلفة لأي متدرب من لوحة التحكم.\n\nمحتوى الدورة: أساسيات حماية الحسابات والبيانات في بيئة العمل اليومية.",
            'what_you_learn' => "إنشاء كلمات مرور قوية وتفعيل التحقق الثنائي\nتمييز رسائل التصيّد والروابط المشبوهة\nالتعامل الآمن مع البيانات الحساسة\nالتصرف الصحيح عند الاشتباه بحادثة أمنية",
            'requirements' => 'جوال أو حاسب متصل بالإنترنت',
            'target_audience' => 'الموظفون في جميع القطاعات',
            'level' => 'beginner',
            'duration_text' => '5 أيام دراسة',
            'price' => 0,
            'certificate_enabled' => true,
            'daily_release' => true,
            'lessons_per_day' => 1,
            'is_published' => true,
            'is_featured' => true,
            'sort' => 1,
        ]);

        $lessons = [
            ['اليوم الأول: لماذا الأمن السيبراني مسؤولية الجميع؟', "أغلب الحوادث الأمنية تبدأ بخطأ بشري بسيط: رابط مفتوح، كلمة مرور ضعيفة، أو جهاز غير مقفل.\n\nفي هذه الدورة ستتعلم عادات يومية بسيطة تحمي حساباتك وبيانات جهة عملك.\n\nتمرين: اكتب 3 حسابات مهمة لديك (البريد، البنك، حساب العمل) — سنحميها في الدروس القادمة."],
            ['اليوم الثاني: كلمات المرور والتحقق الثنائي', "كلمة المرور القوية: طويلة (12 حرفًا أو أكثر)، وغير مستخدمة في موقع آخر.\nاستخدم عبارة مرور يسهل تذكرها ويصعب تخمينها.\n\nفعّل التحقق الثنائي (رمز يصل لجوالك) في كل حساب يدعمه.\n\nتمرين: فعّل التحقق الثنائي في بريدك الإلكتروني اليوم."],
            ['اليوم الثالث: رسائل التصيّد والروابط المشبوهة', "علامات رسالة التصيّد:\n- استعجال وتهديد (\"سيُغلق حسابك خلال ساعة\")\n- رابط لا يطابق اسم الجهة الحقيقي\n- طلب بيانات سرية أو رمز تحقق\n\nالقاعدة الذهبية: لا تشارك رمز التحقق مع أي أحد، ولا جهة رسمية تطلبه منك."],
            ['اليوم الرابع: حماية البيانات في العمل', "صنّف البيانات: عامة، داخلية، سرية.\nلا ترسل البيانات السرية عبر قنوات شخصية.\nاقفل جهازك عند الابتعاد عنه.\nاحذر من أجهزة USB المجهولة وشبكات الواي فاي العامة."],
            ['اليوم الخامس: ماذا أفعل عند الاشتباه بحادثة؟', "إذا ضغطت على رابط مشبوه أو لاحظت نشاطًا غريبًا:\n1) افصل الجهاز عن الشبكة إن أمكن.\n2) غيّر كلمة المرور من جهاز آخر.\n3) أبلغ قسم تقنية المعلومات فورًا.\n\nالإبلاغ السريع يقلل الضرر — لا تتردد ولا تخفِ الخطأ."],
        ];

        $topic = $course->topics()->create(['title' => 'دروس الدورة', 'sort' => 1]);
        foreach ($lessons as $i => [$lessonTitle, $content]) {
            $topic->lessons()->create([
                'course_id' => $course->id, 'title' => $lessonTitle, 'content' => $content,
                'duration' => '15:00', 'is_preview' => $i === 0, 'sort' => $i + 1,
            ]);
        }

        $quiz = $topic->quizzes()->create([
            'course_id' => $course->id, 'sort' => 10,
            'title' => 'اختبار نهاية الدورة',
            'description' => 'يُفتح بعد إكمال الدروس الخمسة. درجة النجاح 60%.',
            'pass_mark' => 60,
        ]);
        $quiz->questions()->create([
            'sort' => 1, 'type' => 'true_false', 'points' => 1,
            'question' => 'يجوز مشاركة رمز التحقق (OTP) مع موظف البنك إذا اتصل بك.',
            'options' => [['text' => 'صح', 'correct' => false], ['text' => 'خطأ', 'correct' => true]],
            'explanation' => 'لا جهة رسمية تطلب رمز التحقق — مشاركته تعني تسليم حسابك.',
        ]);
        $quiz->questions()->create([
            'sort' => 2, 'type' => 'single', 'points' => 1,
            'question' => 'ما أول خطوة عند الضغط على رابط مشبوه؟',
            'options' => [['text' => 'تجاهل الأمر', 'correct' => false], ['text' => 'فصل الجهاز عن الشبكة وإبلاغ تقنية المعلومات', 'correct' => true], ['text' => 'إعادة تشغيل الجهاز فقط', 'correct' => false]],
        ]);
        $quiz->questions()->create([
            'sort' => 3, 'type' => 'multiple', 'points' => 1,
            'question' => 'اختر علامات رسائل التصيّد:',
            'options' => [['text' => 'الاستعجال والتهديد', 'correct' => true], ['text' => 'رابط لا يطابق اسم الجهة', 'correct' => true], ['text' => 'رسالة من زميل تؤكد موعد اجتماع معروف', 'correct' => false], ['text' => 'طلب رمز التحقق', 'correct' => true]],
        ]);
    }
}
